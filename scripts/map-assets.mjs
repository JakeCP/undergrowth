// Dev script: turns the campaign map's painted art into the WebP files
// the game ships, and keeps js/ui/map-assets.js and the service
// worker's precache list in step with what is on disk. Modelled on
// scripts/title-assets.mjs.
//
//   node scripts/map-assets.mjs
//
// Sources (PNG, git-ignored; each one optional, the map works without):
//   assets/map/<plate>.png            region plates (1024x1536) -> 1024 px wide
//   assets/map/markers/<name>.png     markers on transparent    -> 256 px square
//   assets/map/markers/mist.png       the mist over unreached land -> 512 px
//   assets/ui/<icon>.png              interface icons            -> 96 px
//
// Only what the game uses is shipped: the plates of the regions in
// data/campaign.js, the landmark of each level there, the home camp,
// trading post, stake, sapling and mist markers, and the three icons.
// Any other WebP left in those folders (an old landmark, say) is
// removed. Plates are encoded at the highest quality that keeps each
// one at PLATE_TARGET_BYTES or less. Running this twice changes nothing.
// This script itself is never precached.
//
// When anything shipped has changed it also bumps APP_VERSION in sw.js
// and refreshes precache-hash.txt, as tests/pwa.test.mjs expects. This
// is not part of the deploy: there is still no build step.
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { pngSize, webpSize, bumpVersion } from './textures.mjs';
import { REGIONS, CAMPAIGN_NODES } from '../data/campaign.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export const PLATE_DIR = 'assets/map';
export const MARKER_DIR = 'assets/map/markers';
export const ICON_DIR = 'assets/ui';
export const LIST_FILE = 'js/ui/map-assets.js';
/** Plates, markers and icons together, at most, in bytes. */
export const BUDGET_BYTES = 900 * 1024;
/** Each plate, at most, in bytes (the quality is lowered until it fits). */
export const PLATE_TARGET_BYTES = 150 * 1024;
/** Shipped widths in pixels. */
export const PLATE_WIDTH = 1024;
export const MARKER_SIZE = 256;
export const MIST_SIZE = 512;
export const ICON_SIZE = 96;
/** The markers every map uses, whatever its levels. */
export const FIXED_MARKERS = Object.freeze(['home-camp', 'trading-post', 'stake', 'sapling', 'mist']);
export const ICONS = Object.freeze(['seed', 'den', 'forest']);
/** Plate qualities to try, best first. */
const PLATE_QUALITIES = [82, 76, 70, 64, 58, 52, 46, 40];
const MARKER_QUALITY = 80;
const ICON_QUALITY = 85;
const ALPHA_QUALITY = 85;

/**
 * @typedef {'plates'|'markers'|'icons'} Group
 * @typedef {{group: Group, key: string, dir: string, width: number, alpha: boolean}} Wanted
 * @typedef {{plates: Record<string, string>, markers: Record<string, string>, icons: Record<string, string>}} MapAssets
 */

/**
 * Every shipped image the game uses, in list order: plates bottom
 * first, then the markers (fixed ones, then landmarks in campaign
 * order), then the icons.
 * @param {ReadonlyArray<{plate: string}>} regions
 * @param {ReadonlyArray<{landmark?: string}>} nodes
 * @returns {Wanted[]}
 */
export function wantedAssets(regions = REGIONS, nodes = CAMPAIGN_NODES) {
  /** @type {Wanted[]} */
  const out = [];
  for (const r of regions) out.push({ group: 'plates', key: r.plate, dir: PLATE_DIR, width: PLATE_WIDTH, alpha: false });
  const markers = [...FIXED_MARKERS];
  for (const n of nodes) if (n.landmark !== undefined && !markers.includes(n.landmark)) markers.push(n.landmark);
  for (const key of markers) {
    out.push({ group: 'markers', key, dir: MARKER_DIR, width: key === 'mist' ? MIST_SIZE : MARKER_SIZE, alpha: true });
  }
  for (const key of ICONS) out.push({ group: 'icons', key, dir: ICON_DIR, width: ICON_SIZE, alpha: true });
  return out;
}

/**
 * The source of js/ui/map-assets.js for these shipped files.
 * @param {MapAssets} assets
 * @returns {string}
 */
export function mapAssetsSource(assets) {
  /** @param {Record<string, string>} group */
  const block = (group) => {
    const keys = Object.keys(group);
    if (keys.length === 0) return 'Object.freeze({})';
    return `Object.freeze({\n${keys.map((k) => `    '${k}': '${group[k]}',`).join('\n')}\n  })`;
  };
  return [
    '// Generated by scripts/map-assets.mjs: the campaign map\'s plates and',
    '// markers and the interface icons that exist as shipped WebP files.',
    '// Do not edit by hand; run `node scripts/map-assets.mjs` after adding',
    '// or removing a file.',
    '/** @type {Readonly<{plates: Readonly<Record<string, string>>, markers: Readonly<Record<string, string>>, icons: Readonly<Record<string, string>>}>} */',
    'export const MAP_ASSETS = Object.freeze({',
    `  plates: ${block(assets.plates)},`,
    `  markers: ${block(assets.markers)},`,
    `  icons: ${block(assets.icons)},`,
    '});',
    '',
  ].join('\n');
}

/**
 * sw.js with its precache list listing exactly these map and icon files
 * (sorted). They go where the old ones were; the first time, before the
 * title files (which scripts/title-assets.mjs keeps last), else at the
 * end. Other entries are left as they are.
 * @param {string} sw the source of sw.js
 * @param {string[]} files shipped paths relative to the repo root
 * @returns {string}
 */
export function syncMapPrecache(sw, files) {
  const block = sw.match(/(const PRECACHE_URLS = \[\n)([\s\S]*?)(\];)/);
  if (block === null || block.index === undefined) {
    throw new Error('sw.js must declare const PRECACHE_URLS = [...]');
  }
  const lines = block[2].split('\n').slice(0, -1).map((line) => `${line}\n`);
  const ours = (/** @type {string} */ line) => /^[ \t]*'assets\/(map|ui)\//.test(line);
  let at = lines.findIndex(ours);
  const kept = lines.filter((line) => !ours(line));
  if (at < 0) at = kept.findIndex((line) => /^[ \t]*'assets\/title\//.test(line));
  if (at < 0) at = kept.length;
  const added = [...files].sort().map((file) => `  '${file}',\n`);
  kept.splice(at, 0, ...added);
  return sw.slice(0, block.index) + block[1] + kept.join('') + block[3]
    + sw.slice(block.index + block[0].length);
}

/**
 * @param {string} file
 * @param {string} content
 * @returns {boolean} true when the file had to be written
 */
function writeIfChanged(file, content) {
  if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === content) return false;
  fs.writeFileSync(file, content);
  return true;
}

/**
 * @param {string} src
 * @param {string} dest
 * @returns {boolean} true when dest is missing or older than src
 */
function stale(src, dest) {
  if (!fs.existsSync(dest)) return true;
  return fs.statSync(src).mtimeMs > fs.statSync(dest).mtimeMs;
}

/**
 * One cwebp run.
 * @param {string} src
 * @param {string} dest
 * @param {{width: number, height: number}} to
 * @param {number} quality
 * @param {boolean} alpha
 * @returns {string|null} what went wrong, or null
 */
function cwebp(src, dest, to, quality, alpha) {
  const args = ['-quiet', '-q', String(quality), '-m', '6', '-metadata', 'none'];
  if (alpha) args.push('-alpha_q', String(ALPHA_QUALITY));
  args.push('-resize', String(to.width), String(to.height), src, '-o', dest);
  const done = spawnSync('cwebp', args, { encoding: 'utf8' });
  if (done.error !== undefined) return done.error.message;
  if (done.status !== 0) return (done.stderr || done.stdout || `exit status ${done.status}`).trim();
  if (!fs.existsSync(dest)) return 'no file was written';
  return null;
}

/**
 * Converts one source. Plates step the quality down until the file
 * fits PLATE_TARGET_BYTES.
 * @param {Wanted} want
 * @param {string} src
 * @param {string} dest
 * @param {{width: number, height: number}} from
 * @returns {string|null} what went wrong, or null
 */
function convert(want, src, dest, from) {
  const width = Math.min(want.width, from.width);
  const to = { width, height: Math.max(1, Math.round((from.height * width) / from.width)) };
  if (want.group !== 'plates') {
    return cwebp(src, dest, to, want.group === 'icons' ? ICON_QUALITY : MARKER_QUALITY, want.alpha);
  }
  for (const q of PLATE_QUALITIES) {
    const problem = cwebp(src, dest, to, q, false);
    if (problem !== null) return problem;
    if (fs.statSync(dest).size <= PLATE_TARGET_BYTES) return null;
  }
  return null; // the lowest quality tried; the report shows the size
}

/**
 * @typedef {object} MapAssetsResult
 * @property {boolean} ok no errors
 * @property {string[]} converted shipped paths made on this run
 * @property {string[]} removed shipped paths deleted as unused
 * @property {MapAssets} assets what exists now
 * @property {Record<string, {width: number, height: number, bytes: number}>} files by shipped path
 * @property {string[]} missing wanted images with neither source nor WebP
 * @property {string[]} warnings
 * @property {string[]} errors
 * @property {number} totalBytes
 * @property {boolean} changed a shipped file changed: bump APP_VERSION
 *   and refresh the precache hash
 */

/**
 * Converts the sources under `root`, removes unused WebP files, then
 * brings the asset list and the precache list in `root`'s sw.js up to
 * date. It does not bump the version or touch the precache hash; the
 * command line does that.
 * @param {{root?: string, regions?: ReadonlyArray<{plate: string}>, nodes?: ReadonlyArray<{landmark?: string}>}} [options]
 * @returns {MapAssetsResult}
 */
export function run(options = {}) {
  const root = options.root ?? ROOT;
  const wanted = wantedAssets(options.regions, options.nodes);
  const hasCwebp = spawnSync('cwebp', ['-version'], { encoding: 'utf8' }).status === 0;
  /** @type {string[]} */
  const converted = [];
  /** @type {string[]} */
  const removed = [];
  /** @type {string[]} */
  const missing = [];
  /** @type {string[]} */
  const warnings = [];
  /** @type {string[]} */
  const errors = [];
  let changed = false;

  for (const want of wanted) {
    const src = path.join(root, want.dir, `${want.key}.png`);
    const rel = `${want.dir}/${want.key}.webp`;
    const dest = path.join(root, rel);
    if (!fs.existsSync(src)) {
      if (!fs.existsSync(dest)) missing.push(rel);
      continue;
    }
    if (!stale(src, dest)) continue;
    if (!hasCwebp) {
      errors.push(`cwebp was not found, so ${want.dir}/${want.key}.png was not converted. Install it (brew install webp) and run this again.`);
      continue;
    }
    const size = pngSize(fs.readFileSync(src));
    if (size === null) {
      errors.push(`${want.dir}/${want.key}.png is not a PNG image: not converted`);
      continue;
    }
    const before = fs.existsSync(dest) ? fs.readFileSync(dest) : null;
    const problem = convert(want, src, dest, size);
    if (problem !== null) {
      errors.push(`${want.dir}/${want.key}.png could not be converted: ${problem}`);
      continue;
    }
    converted.push(rel);
    if (before === null || !before.equals(fs.readFileSync(dest))) changed = true;
  }

  // Ship only what is used: any other WebP in these folders goes.
  const keep = new Set(wanted.map((w) => `${w.dir}/${w.key}.webp`));
  for (const dir of [PLATE_DIR, MARKER_DIR, ICON_DIR]) {
    const full = path.join(root, dir);
    if (!fs.existsSync(full)) continue;
    for (const name of fs.readdirSync(full).sort()) {
      const rel = `${dir}/${name}`;
      if (!name.endsWith('.webp') || keep.has(rel)) continue;
      fs.rmSync(path.join(full, name));
      removed.push(rel);
      changed = true;
    }
  }

  /** @type {MapAssets} */
  const assets = { plates: {}, markers: {}, icons: {} };
  /** @type {Record<string, {width: number, height: number, bytes: number}>} */
  const files = {};
  let totalBytes = 0;
  for (const want of wanted) {
    const rel = `${want.dir}/${want.key}.webp`;
    const file = path.join(root, rel);
    if (!fs.existsSync(file)) continue;
    const data = fs.readFileSync(file);
    const size = webpSize(data);
    assets[want.group][want.key] = rel;
    files[rel] = { width: size?.width ?? 0, height: size?.height ?? 0, bytes: data.length };
    totalBytes += data.length;
    if (size === null) warnings.push(`${rel} is not a WebP image`);
    else if (size.width > want.width) warnings.push(`${rel} is ${size.width} px wide, over ${want.width}`);
    if (want.group === 'plates' && data.length > PLATE_TARGET_BYTES) {
      warnings.push(`${rel} is ${kb(data.length)} even at the lowest quality tried, over ${kb(PLATE_TARGET_BYTES)}`);
    }
  }
  if (totalBytes > BUDGET_BYTES) {
    errors.push(`The map art adds up to ${kb(totalBytes)}, over the ${kb(BUDGET_BYTES)} budget`);
  }

  if (writeIfChanged(path.join(root, LIST_FILE), mapAssetsSource(assets))) changed = true;
  const shipped = Object.keys(files);
  const swFile = path.join(root, 'sw.js');
  if (writeIfChanged(swFile, syncMapPrecache(fs.readFileSync(swFile, 'utf8'), shipped))) changed = true;

  return { ok: errors.length === 0, converted, removed, assets, files, missing, warnings, errors, totalBytes, changed };
}

/**
 * @param {number} bytes
 * @returns {string}
 */
function kb(bytes) {
  return `${(bytes / 1024).toFixed(1)} KB`;
}

/**
 * The report printed after a run.
 * @param {MapAssetsResult} result
 * @returns {string}
 */
export function formatReport(result) {
  const lines = ['Map art (plates 1024 px wide, markers 256 px, mist 512 px, icons 96 px)'];
  for (const [rel, file] of Object.entries(result.files)) {
    const how = result.converted.includes(rel) ? 'converted' : 'already there';
    lines.push(`  ${rel.padEnd(44)} ${`${file.width}x${file.height}`.padEnd(10)} ${kb(file.bytes).padStart(9)}  ${how}`);
  }
  for (const rel of result.missing) lines.push(`  ${rel.padEnd(44)} -          no source: the map falls back`);
  for (const rel of result.removed) lines.push(`  ${rel.padEnd(44)} removed: the game does not use it`);
  lines.push(`Total: ${kb(result.totalBytes)} of the ${kb(BUDGET_BYTES)} budget.`);
  for (const warning of result.warnings) lines.push(`Warning: ${warning}`);
  for (const error of result.errors) lines.push(`ERROR: ${error}`);
  return lines.join('\n');
}

function main() {
  const result = run();
  console.log(formatReport(result));
  if (result.changed) {
    const swFile = path.join(ROOT, 'sw.js');
    const bumped = bumpVersion(fs.readFileSync(swFile, 'utf8'));
    fs.writeFileSync(swFile, bumped);
    const hashed = spawnSync(process.execPath, [path.join(ROOT, 'scripts/precache-hash.mjs')], { encoding: 'utf8' });
    const version = bumped.match(/const APP_VERSION = '(\d+)';/)?.[1];
    if (hashed.status === 0) {
      console.log(`\nShipped files changed: APP_VERSION is now ${version} and precache-hash.txt is refreshed.`);
    } else {
      console.log(`\nAPP_VERSION is now ${version}, but the precache hash could not be refreshed:`);
      console.log((hashed.stderr || hashed.stdout || '').trim());
      console.log('Run `npm run precache-hash` once that is fixed.');
      process.exitCode = 1;
    }
  }
  if (!result.ok) process.exitCode = 1;
}

if (process.argv[1] !== undefined && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
