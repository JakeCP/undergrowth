// Dev script: turns the battle board's painted pieces (trees, rocks,
// dens, holes, dams, stumps, small details and the permit) into the WebP
// files the game ships, and keeps js/ui/board-assets.js and the service
// worker's precache list in step with what is on disk. Modelled on
// scripts/map-assets.mjs and scripts/shop-assets.mjs.
//
//   node scripts/board-assets.mjs
//
// Sources (PNG, git-ignored; each one optional, docs/art/board-sprite-
// prompts.md says how they were made): assets/board/<piece>.png, square,
// one object on a transparent background. Each is shrunk to 192 px
// square, keeping its alpha. The pieces are encoded at the highest
// quality that keeps them all within BUDGET_BYTES together. A piece with
// no WebP is drawn in code, as before (js/ui/board-pieces.js). A PNG
// whose name is not a piece the game draws is reported and not shipped,
// and any other WebP in the folder is removed. Running this twice
// changes nothing. This script itself is never precached.
//
// When anything shipped has changed it also bumps APP_VERSION in sw.js
// and refreshes precache-hash.txt, as tests/pwa.test.mjs expects. This
// is not part of the deploy: there is still no build step.
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { pngSize, webpSize, bumpVersion } from './textures.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export const BOARD_DIR = 'assets/board';
export const LIST_FILE = 'js/ui/board-assets.js';
/** All the board pieces together, at most, in bytes. */
export const BUDGET_BYTES = 300 * 1024;
/** Shipped size in pixels (square). */
export const SIZE = 192;
/** Qualities to try, best first, until the pieces fit the budget. */
const QUALITIES = [82, 76, 70, 64, 58, 52];
const ALPHA_QUALITY = 90;

/**
 * Every piece the board can draw, in list-file order.
 * @type {readonly string[]}
 */
export const PIECES = Object.freeze([
  'forest-pines', 'forest-birches', 'forest-bushes', 'forest-mixed',
  'stones-1', 'stones-2',
  'den-burrow', 'den-burrow-damaged', 'den-anthill', 'den-anthill-damaged',
  'den-nest', 'den-nest-damaged', 'den-hive', 'den-hive-damaged',
  'hole', 'dam', 'stump',
  'flowers-white', 'flowers-violet', 'mushrooms', 'fern',
  'permit',
]);

/**
 * The source of js/ui/board-assets.js for these shipped files.
 * @param {Record<string, string>} assets piece name -> shipped path
 * @returns {string}
 */
export function boardAssetsSource(assets) {
  const lines = PIECES.filter((p) => assets[p] !== undefined).map((p) => `  '${p}': '${assets[p]}',`);
  return [
    '// Generated by scripts/board-assets.mjs: the battle board\'s painted',
    '// pieces that exist as shipped WebP files under assets/board/. Do not',
    '// edit by hand; run `node scripts/board-assets.mjs` after adding or',
    '// removing a file.',
    '/** @type {Readonly<Record<string, string>>} */',
    lines.length === 0
      ? 'export const BOARD_ASSETS = Object.freeze({});'
      : `export const BOARD_ASSETS = Object.freeze({\n${lines.join('\n')}\n});`,
    '',
  ].join('\n');
}

/**
 * sw.js with its precache list listing exactly these board files
 * (sorted). They go where the old ones were; the first time, before the
 * title files (which scripts/title-assets.mjs keeps last), else at the
 * end. Other entries are left as they are.
 * @param {string} sw the source of sw.js
 * @param {string[]} files shipped paths relative to the repo root
 * @returns {string}
 */
export function syncBoardPrecache(sw, files) {
  const block = sw.match(/(const PRECACHE_URLS = \[\n)([\s\S]*?)(\];)/);
  if (block === null || block.index === undefined) {
    throw new Error('sw.js must declare const PRECACHE_URLS = [...]');
  }
  const lines = block[2].split('\n').slice(0, -1).map((line) => `${line}\n`);
  const ours = (/** @type {string} */ line) => /^[ \t]*'assets\/board\//.test(line);
  let at = lines.findIndex(ours);
  const kept = lines.filter((line) => !ours(line));
  if (at < 0) at = kept.findIndex((line) => /^[ \t]*'assets\/title\//.test(line));
  if (at < 0) at = kept.length;
  const added = [...files].sort().map((file) => `  '${file}',\n`);
  kept.splice(at, 0, ...added);
  return sw.slice(0, block.index) + block[1] + kept.join('') + block[3]
    + sw.slice(block.index + block[0].length);
}

/**
 * @param {string} file
 * @param {string} content
 * @returns {boolean} true when the file had to be written
 */
function writeIfChanged(file, content) {
  if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === content) return false;
  fs.writeFileSync(file, content);
  return true;
}

/**
 * One cwebp run, keeping the alpha channel.
 * @param {string} cwebp
 * @param {string} src
 * @param {string} dest
 * @param {number} quality
 * @returns {string|null} what went wrong, or null
 */
function encode(cwebp, src, dest, quality) {
  const args = [
    '-quiet', '-q', String(quality), '-m', '6', '-metadata', 'none', '-alpha_q', String(ALPHA_QUALITY),
    '-resize', String(SIZE), String(SIZE), src, '-o', dest,
  ];
  const done = spawnSync(cwebp, args, { encoding: 'utf8' });
  if (done.error !== undefined) return done.error.message;
  if (done.status !== 0) return (done.stderr || done.stdout || `exit status ${done.status}`).trim();
  if (!fs.existsSync(dest)) return 'no file was written';
  return null;
}

/**
 * The cwebp command on this machine, or null.
 * @returns {string|null}
 */
function findCwebp() {
  for (const cmd of ['cwebp', '/opt/homebrew/bin/cwebp']) {
    const probe = spawnSync(cmd, ['-version'], { encoding: 'utf8' });
    if (probe.error === undefined && probe.status === 0) return cmd;
  }
  return null;
}

/**
 * @typedef {object} BoardAssetsResult
 * @property {boolean} ok no errors
 * @property {string[]} converted shipped paths made on this run
 * @property {string[]} removed shipped paths deleted as unused
 * @property {Record<string, string>} assets what exists now, by piece
 * @property {Record<string, {width: number, height: number, bytes: number}>} files by shipped path
 * @property {string[]} missing pieces with neither source nor WebP
 * @property {number} quality the quality used on this run, or 0 when nothing was converted
 * @property {string[]} warnings
 * @property {string[]} errors
 * @property {number} totalBytes
 * @property {boolean} changed a shipped file changed: bump APP_VERSION
 *   and refresh the precache hash
 */

/**
 * Converts the sources under `root` when any is newer than its WebP (all
 * of them, so they share one quality), removes WebP files that are not
 * pieces, then brings the list module and the precache list in `root`'s
 * sw.js up to date. It does not bump the version or touch the precache
 * hash; the command line does that.
 * @param {{root?: string, converter?: string|null}} [options]
 * @returns {BoardAssetsResult}
 */
export function run(options = {}) {
  const root = options.root ?? ROOT;
  const cwebp = options.converter === undefined ? findCwebp() : options.converter;
  const dir = path.join(root, BOARD_DIR);
  /** @type {string[]} */
  const converted = [];
  /** @type {string[]} */
  const removed = [];
  /** @type {string[]} */
  const missing = [];
  /** @type {string[]} */
  const warnings = [];
  /** @type {string[]} */
  const errors = [];
  let changed = false;
  let quality = 0;

  const jobs = PIECES.map((name) => ({
    name,
    src: path.join(dir, `${name}.png`),
    rel: `${BOARD_DIR}/${name}.webp`,
    dest: path.join(dir, `${name}.webp`),
  }));
  const sources = jobs.filter((j) => fs.existsSync(j.src));
  for (const j of jobs) if (!fs.existsSync(j.src) && !fs.existsSync(j.dest)) missing.push(j.rel);
  if (fs.existsSync(dir)) {
    for (const name of fs.readdirSync(dir).sort()) {
      if (name.endsWith('.png') && !PIECES.includes(name.slice(0, -'.png'.length))) {
        warnings.push(`${BOARD_DIR}/${name} is not a piece the board draws: not shipped`);
      }
    }
  }
  const stale = sources.some((j) => !fs.existsSync(j.dest) || fs.statSync(j.src).mtimeMs > fs.statSync(j.dest).mtimeMs);

  if (stale && cwebp === null) {
    errors.push('cwebp was not found, so the board pieces were not converted. Install it (brew install webp) and run this again.');
  } else if (stale && cwebp !== null) {
    /** @type {Map<string, Buffer|null>} */
    const before = new Map(sources.map((j) => [j.dest, fs.existsSync(j.dest) ? fs.readFileSync(j.dest) : null]));
    const ready = sources.filter((j) => {
      const size = pngSize(fs.readFileSync(j.src));
      if (size === null) errors.push(`${BOARD_DIR}/${j.name}.png is not a PNG image: not converted`);
      else if (size.width !== size.height) warnings.push(`${BOARD_DIR}/${j.name}.png is ${size.width}x${size.height}, not square: it is squashed to ${SIZE} px square`);
      return size !== null;
    });
    // The pieces already shipped that are not converted now still count.
    const others = jobs.filter((j) => !ready.includes(j) && fs.existsSync(j.dest))
      .reduce((sum, j) => sum + fs.statSync(j.dest).size, 0);
    for (const q of QUALITIES) {
      quality = q;
      let failed = false;
      for (const j of ready) {
        const problem = encode(cwebp, j.src, j.dest, q);
        if (problem !== null) {
          errors.push(`${BOARD_DIR}/${j.name}.png could not be converted: ${problem}`);
          failed = true;
        }
      }
      if (failed) break;
      const total = others + ready.reduce((sum, j) => sum + fs.statSync(j.dest).size, 0);
      if (total <= BUDGET_BYTES) break;
    }
    for (const j of ready) {
      if (!fs.existsSync(j.dest)) continue;
      converted.push(j.rel);
      const was = before.get(j.dest);
      if (was === null || was === undefined || !was.equals(fs.readFileSync(j.dest))) changed = true;
    }
  }

  // Ship only pieces: any other WebP in the folder goes.
  if (fs.existsSync(dir)) {
    const keep = new Set(PIECES.map((p) => `${p}.webp`));
    for (const name of fs.readdirSync(dir).sort()) {
      if (!name.endsWith('.webp') || keep.has(name)) continue;
      fs.rmSync(path.join(dir, name));
      removed.push(`${BOARD_DIR}/${name}`);
      changed = true;
    }
  }

  /** @type {Record<string, string>} */
  const assets = {};
  /** @type {Record<string, {width: number, height: number, bytes: number}>} */
  const files = {};
  let totalBytes = 0;
  for (const j of jobs) {
    if (!fs.existsSync(j.dest)) continue;
    const data = fs.readFileSync(j.dest);
    const size = webpSize(data);
    assets[j.name] = j.rel;
    files[j.rel] = { width: size?.width ?? 0, height: size?.height ?? 0, bytes: data.length };
    totalBytes += data.length;
    if (size === null) warnings.push(`${j.rel} is not a WebP image`);
    else if (size.width > SIZE || size.height > SIZE) warnings.push(`${j.rel} is ${size.width}x${size.height}, over ${SIZE} px`);
  }
  if (totalBytes > BUDGET_BYTES) {
    errors.push(`The board pieces add up to ${kb(totalBytes)}, over the ${kb(BUDGET_BYTES)} budget`);
  }

  if (writeIfChanged(path.join(root, LIST_FILE), boardAssetsSource(assets))) changed = true;
  const swFile = path.join(root, 'sw.js');
  if (writeIfChanged(swFile, syncBoardPrecache(fs.readFileSync(swFile, 'utf8'), Object.keys(files)))) changed = true;

  return { ok: errors.length === 0, converted, removed, assets, files, missing, quality, warnings, errors, totalBytes, changed };
}

/**
 * @param {number} bytes
 * @returns {string}
 */
function kb(bytes) {
  return `${(bytes / 1024).toFixed(1)} KB`;
}

/**
 * The report printed after a run.
 * @param {BoardAssetsResult} result
 * @returns {string}
 */
export function formatReport(result) {
  const lines = [`Battle board pieces (${SIZE} px square)`];
  for (const [rel, file] of Object.entries(result.files)) {
    const how = result.converted.includes(rel) ? `converted at quality ${result.quality}` : 'already there';
    lines.push(`  ${rel.padEnd(40)} ${`${file.width}x${file.height}`.padEnd(8)} ${kb(file.bytes).padStart(9)}  ${how}`);
  }
  for (const rel of result.missing) lines.push(`  ${rel.padEnd(40)} -        no source: drawn in code`);
  for (const rel of result.removed) lines.push(`  ${rel.padEnd(40)} removed: not a board piece`);
  lines.push(`Total: ${kb(result.totalBytes)} of the ${kb(BUDGET_BYTES)} budget.`);
  for (const warning of result.warnings) lines.push(`Warning: ${warning}`);
  for (const error of result.errors) lines.push(`ERROR: ${error}`);
  return lines.join('\n');
}

function main() {
  const result = run();
  console.log(formatReport(result));
  if (result.changed) {
    const swFile = path.join(ROOT, 'sw.js');
    const bumped = bumpVersion(fs.readFileSync(swFile, 'utf8'));
    fs.writeFileSync(swFile, bumped);
    const hashed = spawnSync(process.execPath, [path.join(ROOT, 'scripts/precache-hash.mjs')], { encoding: 'utf8' });
    const version = bumped.match(/const APP_VERSION = '(\d+)';/)?.[1];
    if (hashed.status === 0) {
      console.log(`\nShipped files changed: APP_VERSION is now ${version} and precache-hash.txt is refreshed.`);
    } else {
      console.log(`\nAPP_VERSION is now ${version}, but the precache hash could not be refreshed:`);
      console.log((hashed.stderr || hashed.stdout || '').trim());
      console.log('Run `npm run precache-hash` once that is fixed.');
      process.exitCode = 1;
    }
  }
  if (!result.ok) process.exitCode = 1;
}

if (process.argv[1] !== undefined && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
