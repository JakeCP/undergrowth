// Dev script: turns the painted interface kit (buttons, panels, ribbons,
// the canopy backdrop, the two result scenes and the action emblems) into
// the WebP files the game ships, and keeps js/ui/ui-assets.js and the
// service worker's precache list in step with what is on disk. Modelled
// on scripts/map-assets.mjs and scripts/board-assets.mjs.
//
//   node scripts/ui-assets.mjs
//
// Sources (PNG, git-ignored; each one optional, docs/art/ui-kit-prompts.md
// says how they were made): assets/ui/<piece>.png. The three small
// interface icons in the same folder (seed, den, forest) belong to
// scripts/map-assets.mjs and are left alone; the spares in
// assets/ui/alternates/ are never read.
//
// The kit ships in assets/kit/, at twice phone density for the size
// it is shown at and no more (KIT below). Before encoding, every cut-out
// is cleaned (scripts/png.mjs, cleanCutout): the image tool left
// speckles of nearly transparent red and yellow round the pieces and a
// soft halo, which would show as a coloured fringe on the dark backdrop.
// Pixels under an alpha floor go, small islands go, one pixel of halo is
// trimmed and the soft edge takes the colour of the paint beside it. Each
// cut-out is then cropped to the piece (an emblem to a square round it),
// so the slice insets in css/ui.css measure the piece and not its empty
// margin. The backdrop's opposite edges do not quite meet, so a seam
// showed when it was tiled; it is made seamless by fading in a copy of
// itself shifted by half (seamlessTile), not by mirroring it.
//
// The whole kit stays within BUDGET_BYTES: the qualities are lowered
// together until it fits. A piece with no WebP falls back to a
// code-drawn look (css/ui.css, js/ui/ui-kit.js). Any other WebP in
// assets/kit/ is removed. Running this twice changes nothing. This
// script itself is never precached.
//
// When anything shipped has changed it also bumps APP_VERSION in sw.js
// and refreshes precache-hash.txt, as tests/pwa.test.mjs expects. This
// is not part of the deploy: there is still no build step.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { webpSize, bumpVersion } from './textures.mjs';
import { decodePng, encodePng, cleanCutout, trim, resize, seamlessTile, seamScore } from './png.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export const SOURCE_DIR = 'assets/ui';
export const KIT_DIR = 'assets/kit';
export const LIST_FILE = 'js/ui/ui-assets.js';
/** The whole kit together, at most, in bytes. */
export const BUDGET_BYTES = 900 * 1024;

/**
 * @typedef {'cutout'|'emblem'|'tile'|'scene'} Kind
 * @typedef {{key: string, kind: Kind, width: number}} KitPiece
 */

/**
 * Every piece of the kit, in list-file order, with how it is made and its
 * shipped width in pixels (twice what a phone shows at most). Cut-outs
 * keep their shape (cropped to the piece); emblems and the round button
 * are square; the backdrop and the scenes are opaque.
 * @type {ReadonlyArray<KitPiece>}
 */
export const KIT = Object.freeze([
  { key: 'button-primary', kind: 'cutout', width: 900 },
  { key: 'button-secondary', kind: 'cutout', width: 900 },
  { key: 'button-round', kind: 'emblem', width: 192 },
  { key: 'panel-parchment', kind: 'cutout', width: 768 },
  { key: 'panel-wood', kind: 'cutout', width: 768 },
  { key: 'ribbon-green', kind: 'cutout', width: 1200 },
  { key: 'ribbon-rust', kind: 'cutout', width: 1200 },
  { key: 'backdrop', kind: 'tile', width: 512 },
  { key: 'result-victory', kind: 'scene', width: 1280 },
  { key: 'result-defeat', kind: 'scene', width: 1280 },
  ...['bite', 'dig', 'build', 'ram', 'sting', 'maul', 'shove', 'strike']
    .map((id) => ({ key: `action-${id}`, kind: /** @type {Kind} */ ('emblem'), width: 128 })),
].map((p) => Object.freeze(p)));

/** The pieces' names. */
export const PIECES = Object.freeze(KIT.map((p) => p.key));

/** Quality steps, best first: [cut-outs and emblems, opaque pictures]. */
const QUALITIES = [[84, 80], [78, 74], [72, 68], [66, 62], [60, 56], [54, 50]];
const ALPHA_QUALITY = 90;

/**
 * The source of js/ui/ui-assets.js for these shipped files.
 * @param {Record<string, string>} assets piece name -> shipped path
 * @param {Record<string, {width: number, height: number}>} sizes piece name -> pixel size
 * @returns {string}
 */
export function uiAssetsSource(assets, sizes) {
  const keys = PIECES.filter((p) => assets[p] !== undefined);
  const list = keys.map((p) => `  '${p}': '${assets[p]}',`);
  const dims = keys.map((p) => `  '${p}': Object.freeze({ width: ${sizes[p]?.width ?? 0}, height: ${sizes[p]?.height ?? 0} }),`);
  return [
    '// Generated by scripts/ui-assets.mjs: the painted interface kit that',
    '// exists as shipped WebP files under assets/kit/, and each one\'s',
    '// size in pixels. Do not edit by hand; run `node scripts/ui-assets.mjs`',
    '// after adding or removing a source.',
    '/** @type {Readonly<Record<string, string>>} */',
    list.length === 0
      ? 'export const UI_ASSETS = Object.freeze({});'
      : `export const UI_ASSETS = Object.freeze({\n${list.join('\n')}\n});`,
    '',
    '/** @type {Readonly<Record<string, Readonly<{width: number, height: number}>>>} */',
    dims.length === 0
      ? 'export const UI_ASSET_SIZES = Object.freeze({});'
      : `export const UI_ASSET_SIZES = Object.freeze({\n${dims.join('\n')}\n});`,
    '',
  ].join('\n');
}

/**
 * sw.js with its precache list listing exactly these kit files (sorted).
 * They go where the old ones were; the first time, before the title files,
 * else at the end. Other entries are left as they are.
 * @param {string} sw the source of sw.js
 * @param {string[]} files shipped paths relative to the repo root
 * @returns {string}
 */
export function syncUiPrecache(sw, files) {
  const block = sw.match(/(const PRECACHE_URLS = \[\n)([\s\S]*?)(\];)/);
  if (block === null || block.index === undefined) {
    throw new Error('sw.js must declare const PRECACHE_URLS = [...]');
  }
  const lines = block[2].split('\n').slice(0, -1).map((line) => `${line}\n`);
  const ours = (/** @type {string} */ line) => /^[ \t]*'assets\/kit\//.test(line);
  let at = lines.findIndex(ours);
  const kept = lines.filter((line) => !ours(line));
  if (at < 0) at = kept.findIndex((line) => /^[ \t]*'assets\/title\//.test(line));
  if (at < 0) at = kept.length;
  const added = [...files].sort().map((file) => `  '${file}',\n`);
  kept.splice(at, 0, ...added);
  return sw.slice(0, block.index) + block[1] + kept.join('') + block[3]
    + sw.slice(block.index + block[0].length);
}

/**
 * @param {string} file
 * @param {string} content
 * @returns {boolean} true when the file had to be written
 */
function writeIfChanged(file, content) {
  if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === content) return false;
  fs.writeFileSync(file, content);
  return true;
}

/**
 * The cwebp command on this machine, or null.
 * @returns {string|null}
 */
function findCwebp() {
  for (const cmd of ['cwebp', '/opt/homebrew/bin/cwebp']) {
    const probe = spawnSync(cmd, ['-version'], { encoding: 'utf8' });
    if (probe.error === undefined && probe.status === 0) return cmd;
  }
  return null;
}

/**
 * A piece made ready to encode: cleaned, cropped and shrunk.
 * @param {KitPiece} piece
 * @param {Buffer} png
 * @returns {{img: import('./png.mjs').Rgba, opaque: boolean, notes: string[]}}
 */
export function prepare(piece, png) {
  /** @type {string[]} */
  const notes = [];
  let img = decodePng(png);
  if (piece.kind === 'tile' || piece.kind === 'scene') {
    if (piece.kind === 'tile') {
      const before = seamScore(img);
      if (before > 1.25) {
        img = seamlessTile(img, 0.06);
        notes.push(`seam ${before.toFixed(2)} -> ${seamScore(img).toFixed(2)} (made seamless)`);
      }
      const side = Math.min(piece.width, img.width);
      img = resize(img, side, Math.round((side * img.height) / img.width));
    } else {
      const width = Math.min(piece.width, img.width);
      img = resize(img, width, Math.round((width * img.height) / img.width));
    }
    return { img, opaque: true, notes };
  }
  const cleaned = cleanCutout(img);
  notes.push(`cleaned: ${cleaned.faint} faint, ${cleaned.islands} in specks, ${cleaned.halo} halo, ${cleaned.recoloured} edge recoloured`);
  if (piece.kind === 'emblem') {
    // A square round the piece with a little air, so every emblem fills
    // its box alike.
    const box = trim(img, { square: true });
    const pad = Math.round(box.width * 0.03);
    img = trim(img, { square: true, pad });
    img = resize(img, piece.width, piece.width);
  } else {
    img = trim(img, { pad: 2 });
    img = resize(img, piece.width, Math.round((piece.width * img.height) / img.width));
  }
  return { img, opaque: false, notes };
}

/**
 * One cwebp run.
 * @param {string} cwebp
 * @param {string} src a PNG ready to encode at its own size
 * @param {string} dest
 * @param {number} quality
 * @param {boolean} opaque
 * @returns {string|null} what went wrong, or null
 */
function encode(cwebp, src, dest, quality, opaque) {
  const args = ['-quiet', '-q', String(quality), '-m', '6', '-metadata', 'none'];
  if (opaque) args.push('-noalpha');
  else args.push('-alpha_q', String(ALPHA_QUALITY), '-exact');
  args.push(src, '-o', dest);
  const done = spawnSync(cwebp, args, { encoding: 'utf8' });
  if (done.error !== undefined) return done.error.message;
  if (done.status !== 0) return (done.stderr || done.stdout || `exit status ${done.status}`).trim();
  if (!fs.existsSync(dest)) return 'no file was written';
  return null;
}

/**
 * @typedef {object} UiAssetsResult
 * @property {boolean} ok no errors
 * @property {string[]} converted shipped paths made on this run
 * @property {string[]} removed shipped paths deleted as unused
 * @property {Record<string, string>} assets what exists now, by piece
 * @property {Record<string, {width: number, height: number, bytes: number}>} files by shipped path
 * @property {string[]} missing pieces with neither source nor WebP
 * @property {number[]} quality the qualities used on this run, or [] when nothing was converted
 * @property {string[]} notes what the cleaning did, by piece
 * @property {string[]} warnings
 * @property {string[]} errors
 * @property {number} totalBytes
 * @property {boolean} changed a shipped file changed: bump APP_VERSION
 *   and refresh the precache hash
 */

/**
 * Converts the sources under `root` when any is newer than its WebP (all
 * of them, so they share one quality step), removes WebP files that are
 * not pieces, then brings the list module and the precache list in
 * `root`'s sw.js up to date. It does not bump the version or touch the
 * precache hash; the command line does that.
 * @param {{root?: string, converter?: string|null}} [options]
 * @returns {UiAssetsResult}
 */
export function run(options = {}) {
  const root = options.root ?? ROOT;
  const cwebp = options.converter === undefined ? findCwebp() : options.converter;
  const srcDir = path.join(root, SOURCE_DIR);
  const kitDir = path.join(root, KIT_DIR);
  /** @type {string[]} */
  const converted = [];
  /** @type {string[]} */
  const removed = [];
  /** @type {string[]} */
  const missing = [];
  /** @type {string[]} */
  const notes = [];
  /** @type {string[]} */
  const warnings = [];
  /** @type {string[]} */
  const errors = [];
  /** @type {number[]} */
  let quality = [];
  let changed = false;

  const jobs = KIT.map((piece) => ({
    piece,
    src: path.join(srcDir, `${piece.key}.png`),
    rel: `${KIT_DIR}/${piece.key}.webp`,
    dest: path.join(kitDir, `${piece.key}.webp`),
  }));
  const sources = jobs.filter((j) => fs.existsSync(j.src));
  for (const j of jobs) if (!fs.existsSync(j.src) && !fs.existsSync(j.dest)) missing.push(j.rel);
  const stale = sources.some((j) => !fs.existsSync(j.dest) || fs.statSync(j.src).mtimeMs > fs.statSync(j.dest).mtimeMs);

  if (stale && cwebp === null) {
    errors.push('cwebp was not found, so the interface kit was not converted. Install it (brew install webp) and run this again.');
  } else if (stale && cwebp !== null) {
    fs.mkdirSync(kitDir, { recursive: true });
    const work = fs.mkdtempSync(path.join(os.tmpdir(), 'undergrowth-ui-'));
    try {
      /** @type {Map<string, Buffer|null>} */
      const before = new Map(sources.map((j) => [j.dest, fs.existsSync(j.dest) ? fs.readFileSync(j.dest) : null]));
      /** @type {Array<{job: typeof jobs[number], png: string, opaque: boolean}>} */
      const ready = [];
      for (const j of sources) {
        try {
          const { img, opaque, notes: said } = prepare(j.piece, fs.readFileSync(j.src));
          const png = path.join(work, `${j.piece.key}.png`);
          fs.writeFileSync(png, encodePng(img, { opaque }));
          ready.push({ job: j, png, opaque });
          for (const note of said) notes.push(`${j.piece.key}: ${note}`);
        } catch (err) {
          errors.push(`${SOURCE_DIR}/${j.piece.key}.png could not be read: ${err instanceof Error ? err.message : String(err)}`);
        }
      }
      const others = jobs.filter((j) => !ready.some((r) => r.job === j) && fs.existsSync(j.dest))
        .reduce((sum, j) => sum + fs.statSync(j.dest).size, 0);
      for (const step of QUALITIES) {
        quality = step;
        let failed = false;
        for (const r of ready) {
          const problem = encode(cwebp, r.png, r.job.dest, r.opaque ? step[1] : step[0], r.opaque);
          if (problem !== null) {
            errors.push(`${SOURCE_DIR}/${r.job.piece.key}.png could not be converted: ${problem}`);
            failed = true;
          }
        }
        if (failed) break;
        const total = others + ready.reduce((sum, r) => sum + fs.statSync(r.job.dest).size, 0);
        if (total <= BUDGET_BYTES) break;
      }
      for (const r of ready) {
        if (!fs.existsSync(r.job.dest)) continue;
        converted.push(r.job.rel);
        const was = before.get(r.job.dest);
        if (was === null || was === undefined || !was.equals(fs.readFileSync(r.job.dest))) changed = true;
      }
    } finally {
      fs.rmSync(work, { recursive: true, force: true });
    }
  }

  // Ship only pieces: any other WebP in the kit folder goes.
  if (fs.existsSync(kitDir)) {
    const keep = new Set(PIECES.map((p) => `${p}.webp`));
    for (const name of fs.readdirSync(kitDir).sort()) {
      if (!name.endsWith('.webp') || keep.has(name)) continue;
      fs.rmSync(path.join(kitDir, name));
      removed.push(`${KIT_DIR}/${name}`);
      changed = true;
    }
  }

  /** @type {Record<string, string>} */
  const assets = {};
  /** @type {Record<string, {width: number, height: number}>} */
  const sizes = {};
  /** @type {Record<string, {width: number, height: number, bytes: number}>} */
  const files = {};
  let totalBytes = 0;
  for (const j of jobs) {
    if (!fs.existsSync(j.dest)) continue;
    const data = fs.readFileSync(j.dest);
    const size = webpSize(data);
    assets[j.piece.key] = j.rel;
    sizes[j.piece.key] = { width: size?.width ?? 0, height: size?.height ?? 0 };
    files[j.rel] = { width: size?.width ?? 0, height: size?.height ?? 0, bytes: data.length };
    totalBytes += data.length;
    if (size === null) warnings.push(`${j.rel} is not a WebP image`);
    else if (size.width > j.piece.width) warnings.push(`${j.rel} is ${size.width} px wide, over ${j.piece.width}`);
  }
  if (totalBytes > BUDGET_BYTES) {
    errors.push(`The interface kit adds up to ${kb(totalBytes)}, over the ${kb(BUDGET_BYTES)} budget`);
  }

  fs.mkdirSync(path.join(root, path.dirname(LIST_FILE)), { recursive: true });
  if (writeIfChanged(path.join(root, LIST_FILE), uiAssetsSource(assets, sizes))) changed = true;
  const swFile = path.join(root, 'sw.js');
  if (writeIfChanged(swFile, syncUiPrecache(fs.readFileSync(swFile, 'utf8'), Object.keys(files)))) changed = true;

  return { ok: errors.length === 0, converted, removed, assets, files, missing, quality, notes, warnings, errors, totalBytes, changed };
}

/**
 * @param {number} bytes
 * @returns {string}
 */
function kb(bytes) {
  return `${(bytes / 1024).toFixed(1)} KB`;
}

/**
 * The report printed after a run.
 * @param {UiAssetsResult} result
 * @returns {string}
 */
export function formatReport(result) {
  const lines = ['Interface kit'];
  for (const [rel, file] of Object.entries(result.files)) {
    const how = result.converted.includes(rel) ? `converted at quality ${result.quality.join('/')}` : 'already there';
    lines.push(`  ${rel.padEnd(38)} ${`${file.width}x${file.height}`.padEnd(10)} ${kb(file.bytes).padStart(9)}  ${how}`);
  }
  for (const rel of result.missing) lines.push(`  ${rel.padEnd(38)} -          no source: drawn in code`);
  for (const rel of result.removed) lines.push(`  ${rel.padEnd(38)} removed: not a kit piece`);
  lines.push(`Total: ${kb(result.totalBytes)} of the ${kb(BUDGET_BYTES)} budget.`);
  for (const note of result.notes) lines.push(`  ${note}`);
  for (const warning of result.warnings) lines.push(`Warning: ${warning}`);
  for (const error of result.errors) lines.push(`ERROR: ${error}`);
  return lines.join('\n');
}

function main() {
  const result = run();
  console.log(formatReport(result));
  if (result.changed) {
    const swFile = path.join(ROOT, 'sw.js');
    const bumped = bumpVersion(fs.readFileSync(swFile, 'utf8'));
    fs.writeFileSync(swFile, bumped);
    const hashed = spawnSync(process.execPath, [path.join(ROOT, 'scripts/precache-hash.mjs')], { encoding: 'utf8' });
    const version = bumped.match(/const APP_VERSION = '(\d+)';/)?.[1];
    if (hashed.status === 0) {
      console.log(`\nShipped files changed: APP_VERSION is now ${version} and precache-hash.txt is refreshed.`);
    } else {
      console.log(`\nAPP_VERSION is now ${version}, but the precache hash could not be refreshed:`);
      console.log((hashed.stderr || hashed.stdout || '').trim());
      console.log('Run `npm run precache-hash` once that is fixed.');
      process.exitCode = 1;
    }
  }
  if (!result.ok) process.exitCode = 1;
}

if (process.argv[1] !== undefined && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
