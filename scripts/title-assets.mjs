// Dev script: turns the title artwork in assets/title/ into the WebP
// and MP3 files the game ships, and keeps js/ui/title-assets.js and
// the service worker's precache list in step with what is on disk.
// Modelled on scripts/textures.mjs.
//
//   node scripts/title-assets.mjs
//
// Sources (all optional; the screen works with none of them):
//   title-bg.png          tall scene        -> title-bg.webp
//   title-bg-wide.png     16:9 scene        -> title-bg-wide.webp
//   title-cast.png        transparent cast  -> title-cast.webp
//   title-foreground.png  foliage frame     -> title-foreground.webp
//   title-theme.mp3 (or title-theme-source.*) -> title-theme.mp3
//
// Scenes are shrunk to 1280 px or less on the long side; cut-outs
// keep their transparency. The music ships as an MP3 of 1.2 MB or
// less: it is re-encoded with ffmpeg only when larger. PNG and
// source-audio files are git-ignored; only converted files are
// committed. Running this twice changes nothing. This script itself
// is never precached.
//
// When anything shipped has changed it also bumps APP_VERSION in
// sw.js and refreshes precache-hash.txt, as tests/pwa.test.mjs
// expects. This is not part of the deploy: there is still no build
// step.
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { pngSize, webpSize, targetSize, findConverter, bumpVersion } from './textures.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export const TITLE_DIR = 'assets/title';
export const LIST_FILE = 'js/ui/title-assets.js';
/** The longer side of a shipped title image, in pixels, at most. */
export const MAX_LONG_SIDE = 1280;
/** All title images together, at most, in bytes. */
export const IMAGE_BUDGET_BYTES = 1024 * 1024;
/** The shipped music file, at most, in bytes. */
export const MUSIC_BUDGET_BYTES = Math.floor(1.2 * 1024 * 1024);
export const FFMPEG = '/opt/homebrew/bin/ffmpeg';
export const FFPROBE = '/opt/homebrew/bin/ffprobe';
const QUALITY = 80;

/**
 * The title artwork, in list-file order. `alpha` marks the cut-outs,
 * whose transparency the conversion must keep.
 * @type {readonly {key: string, png: string, webp: string, alpha: boolean}[]}
 */
export const IMAGES = Object.freeze([
  { key: 'bg', png: 'title-bg.png', webp: 'title-bg.webp', alpha: false },
  { key: 'bgWide', png: 'title-bg-wide.png', webp: 'title-bg-wide.webp', alpha: false },
  { key: 'cast', png: 'title-cast.png', webp: 'title-cast.webp', alpha: true },
  { key: 'foreground', png: 'title-foreground.png', webp: 'title-foreground.webp', alpha: true },
]);

/** Source-audio names the theme may arrive as, best first. */
export const THEME_SOURCES = Object.freeze([
  'title-theme-source.mp3', 'title-theme-source.wav', 'title-theme-source.m4a',
  'title-theme.wav', 'title-theme.m4a', 'title-theme.ogg', 'title-theme.flac',
]);
export const THEME_FILE = 'title-theme.mp3';

/**
 * @typedef {{bg: string|null, bgWide: string|null, cast: string|null,
 *   foreground: string|null, theme: string|null}} TitleAssets
 */

/**
 * The source of js/ui/title-assets.js for this set of assets.
 * @param {TitleAssets} assets
 * @returns {string}
 */
export function titleAssetsSource(assets) {
  const entry = (/** @type {string|null} */ v) => (v === null ? 'null' : `'${v}'`);
  return [
    '// Generated by scripts/title-assets.mjs: the title artwork that exists',
    '// as shipped files under assets/title/. Do not edit by hand; run',
    '// `node scripts/title-assets.mjs` after adding or removing a file.',
    '/** @type {Readonly<import(\'./title-view.js\').TitleAssets>} */',
    'export const TITLE_ASSETS = Object.freeze({',
    `  bg: ${entry(assets.bg)},`,
    `  bgWide: ${entry(assets.bgWide)},`,
    `  cast: ${entry(assets.cast)},`,
    `  foreground: ${entry(assets.foreground)},`,
    `  theme: ${entry(assets.theme)},`,
    '});',
    '',
  ].join('\n');
}

/**
 * sw.js with its precache list listing exactly these title files
 * (sorted, after every other entry). Other entries are left as they
 * are — including the ground textures scripts/textures.mjs lists.
 * @param {string} sw the source of sw.js
 * @param {string[]} files shipped paths relative to the repo root
 * @returns {string}
 */
export function syncTitlePrecache(sw, files) {
  const block = sw.match(/(const PRECACHE_URLS = \[\n)([\s\S]*?)(\];)/);
  if (block === null || block.index === undefined) {
    throw new Error('sw.js must declare const PRECACHE_URLS = [...]');
  }
  const kept = block[2].replace(/^[ \t]*'assets\/title\/[^']*',?[ \t]*\n/gm, '');
  const added = [...files].sort().map((file) => `  '${file}',\n`).join('');
  return sw.slice(0, block.index) + block[1] + kept + added + block[3]
    + sw.slice(block.index + block[0].length);
}

/**
 * @param {string} file
 * @param {string} content
 * @returns {boolean} true when the file had to be written
 */
function writeIfChanged(file, content) {
  if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === content) return false;
  fs.writeFileSync(file, content);
  return true;
}

/**
 * @param {string} src
 * @param {string} dest
 * @returns {boolean} true when dest is missing or older than src
 */
function stale(src, dest) {
  if (!fs.existsSync(dest)) return true;
  return fs.statSync(src).mtimeMs > fs.statSync(dest).mtimeMs;
}

/**
 * @param {'cwebp'|'sips'} converter
 * @param {string} src
 * @param {string} dest
 * @param {{width: number, height: number}} from the source's size
 * @param {boolean} alpha keep transparency (the cut-outs)
 * @returns {string|null} what went wrong, or null
 */
function convertImage(converter, src, dest, from, alpha) {
  const to = targetSize(from.width, from.height, MAX_LONG_SIDE);
  /** @type {string[]} */
  let args;
  if (converter === 'cwebp') {
    args = ['-quiet', '-q', String(QUALITY), '-m', '6'];
    if (alpha) args.push('-alpha_q', '90');
    if (to.width !== from.width || to.height !== from.height) {
      args.push('-resize', String(to.width), String(to.height));
    }
    args.push(src, '-o', dest);
  } else {
    args = ['-s', 'format', 'webp', '-s', 'formatOptions', String(QUALITY), '-Z', String(MAX_LONG_SIDE), src, '--out', dest];
  }
  const done = spawnSync(converter, args, { encoding: 'utf8' });
  if (done.error !== undefined) return done.error.message;
  if (done.status !== 0) return (done.stderr || done.stdout || `exit status ${done.status}`).trim();
  if (!fs.existsSync(dest)) return 'no file was written';
  return null;
}

/**
 * The length of an audio file in seconds, or null when ffprobe
 * cannot say.
 * @param {string} file
 * @returns {number|null}
 */
function audioSeconds(file) {
  const probe = spawnSync(FFPROBE, [
    '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', file,
  ], { encoding: 'utf8' });
  if (probe.error !== undefined || probe.status !== 0) return null;
  const seconds = Number.parseFloat((probe.stdout || '').trim());
  return Number.isFinite(seconds) && seconds > 0 ? seconds : null;
}

/**
 * The MP3 bitrate (kbps) that fits `seconds` of music in the budget,
 * with headroom for tags and encoder slack, capped at a sane top.
 * @param {number|null} seconds
 * @returns {number}
 */
export function themeBitrateKbps(seconds) {
  if (seconds === null) return 96;
  const fits = Math.floor(((MUSIC_BUDGET_BYTES * 8) / seconds / 1000) * 0.92);
  return Math.max(48, Math.min(160, fits));
}

/**
 * Re-encodes `src` to the shipped MP3 at a budget-fitting bitrate.
 * @param {string} src
 * @param {string} dest
 * @returns {string|null} what went wrong, or null
 */
function convertTheme(src, dest) {
  const kbps = themeBitrateKbps(audioSeconds(src));
  const tmp = `${dest}.tmp.mp3`;
  const done = spawnSync(FFMPEG, [
    '-y', '-v', 'error', '-i', src, '-vn', '-map_metadata', '-1',
    '-codec:a', 'libmp3lame', '-b:a', `${kbps}k`, tmp,
  ], { encoding: 'utf8' });
  if (done.error !== undefined) return done.error.message;
  if (done.status !== 0) return (done.stderr || done.stdout || `exit status ${done.status}`).trim();
  if (!fs.existsSync(tmp)) return 'no file was written';
  fs.renameSync(tmp, dest);
  return null;
}

/**
 * @typedef {object} TitleAssetsResult
 * @property {boolean} ok no errors
 * @property {string[]} converted shipped file names made on this run
 * @property {TitleAssets} assets what exists now
 * @property {Record<string, {width: number, height: number, bytes: number}>} files
 * @property {string[]} warnings
 * @property {string[]} errors
 * @property {number} imageBytes
 * @property {number} musicBytes
 * @property {boolean} changed a shipped file changed: bump APP_VERSION
 *   and refresh the precache hash
 */

/**
 * Converts the sources under `root`, then brings the asset list and
 * the precache list in `root`'s sw.js up to date. It does not bump
 * the version or touch the precache hash; the command line does that.
 * @param {{root?: string, converter?: 'cwebp'|'sips'|null}} [options]
 *   `converter` defaults to whichever this machine has
 * @returns {TitleAssetsResult}
 */
export function run(options = {}) {
  const root = options.root ?? ROOT;
  const converter = options.converter === undefined ? findConverter() : options.converter;
  const dir = path.join(root, TITLE_DIR);
  /** @type {string[]} */
  const converted = [];
  /** @type {string[]} */
  const warnings = [];
  /** @type {string[]} */
  const errors = [];
  let changed = false;

  // Images: convert each PNG source that is new or changed.
  for (const image of IMAGES) {
    const src = path.join(dir, image.png);
    const dest = path.join(dir, image.webp);
    if (!fs.existsSync(src)) continue;
    if (!stale(src, dest)) continue;
    if (converter === null) {
      errors.push(
        `No WebP converter found, so ${TITLE_DIR}/${image.png} was not converted. `
        + 'Install cwebp (brew install webp) and run this script again.',
      );
      continue;
    }
    const size = pngSize(fs.readFileSync(src));
    if (size === null) {
      errors.push(`${TITLE_DIR}/${image.png} is not a PNG image: not converted`);
      continue;
    }
    const before = fs.existsSync(dest) ? fs.readFileSync(dest) : null;
    const problem = convertImage(converter, src, dest, size, image.alpha);
    if (problem !== null) {
      errors.push(`${TITLE_DIR}/${image.png} could not be converted with ${converter}: ${problem}`);
      continue;
    }
    converted.push(image.webp);
    if (before === null || !before.equals(fs.readFileSync(dest))) changed = true;
  }

  // Music: a distinct source file wins; else an over-budget shipped
  // MP3 is re-encoded in place; an in-budget one ships as it is.
  const themeDest = path.join(dir, THEME_FILE);
  const themeSource = THEME_SOURCES
    .map((name) => path.join(dir, name))
    .find((file) => fs.existsSync(file));
  if (themeSource !== undefined) {
    if (stale(themeSource, themeDest)) {
      const before = fs.existsSync(themeDest) ? fs.readFileSync(themeDest) : null;
      const problem = convertTheme(themeSource, themeDest);
      if (problem !== null) {
        errors.push(`The title theme could not be encoded with ffmpeg: ${problem}`);
      } else {
        converted.push(THEME_FILE);
        if (before === null || !before.equals(fs.readFileSync(themeDest))) changed = true;
      }
    }
  } else if (fs.existsSync(themeDest) && fs.statSync(themeDest).size > MUSIC_BUDGET_BYTES) {
    const problem = convertTheme(themeDest, themeDest);
    if (problem !== null) {
      errors.push(`The title theme could not be re-encoded with ffmpeg: ${problem}`);
    } else {
      converted.push(THEME_FILE);
      changed = true;
    }
  }

  // What exists now.
  /** @type {TitleAssets} */
  const assets = { bg: null, bgWide: null, cast: null, foreground: null, theme: null };
  /** @type {Record<string, {width: number, height: number, bytes: number}>} */
  const files = {};
  let imageBytes = 0;
  for (const image of IMAGES) {
    const file = path.join(dir, image.webp);
    if (!fs.existsSync(file)) continue;
    const data = fs.readFileSync(file);
    const size = webpSize(data);
    const key = /** @type {'bg'|'bgWide'|'cast'|'foreground'} */ (image.key);
    assets[key] = `${TITLE_DIR}/${image.webp}`;
    files[image.webp] = { width: size?.width ?? 0, height: size?.height ?? 0, bytes: data.length };
    imageBytes += data.length;
    if (size === null) {
      warnings.push(`${TITLE_DIR}/${image.webp} is not a WebP image`);
    } else if (Math.max(size.width, size.height) > MAX_LONG_SIDE) {
      warnings.push(`${TITLE_DIR}/${image.webp} is ${size.width}x${size.height}: over ${MAX_LONG_SIDE} px on the long side`);
    }
  }
  if (imageBytes > IMAGE_BUDGET_BYTES) {
    warnings.push(`The title images add up to ${kb(imageBytes)}, over the ${kb(IMAGE_BUDGET_BYTES)} budget`);
    errors.push('Title images are over the 1 MB budget: use smaller or simpler images');
  }
  let musicBytes = 0;
  if (fs.existsSync(themeDest)) {
    musicBytes = fs.statSync(themeDest).size;
    assets.theme = `${TITLE_DIR}/${THEME_FILE}`;
    files[THEME_FILE] = { width: 0, height: 0, bytes: musicBytes };
    if (musicBytes > MUSIC_BUDGET_BYTES) {
      errors.push(`The title theme is ${kb(musicBytes)}, over the ${kb(MUSIC_BUDGET_BYTES)} budget`);
    }
  }

  if (writeIfChanged(path.join(root, LIST_FILE), titleAssetsSource(assets))) changed = true;
  const shipped = Object.values(assets).filter((v) => v !== null);
  const swFile = path.join(root, 'sw.js');
  if (writeIfChanged(swFile, syncTitlePrecache(fs.readFileSync(swFile, 'utf8'), shipped))) changed = true;

  return {
    ok: errors.length === 0,
    converted,
    assets,
    files,
    warnings,
    errors,
    imageBytes,
    musicBytes,
    changed,
  };
}

/**
 * @param {number} bytes
 * @returns {string}
 */
function kb(bytes) {
  return `${(bytes / 1024).toFixed(1)} KB`;
}

/**
 * The report printed after a run.
 * @param {TitleAssetsResult} result
 * @returns {string}
 */
export function formatReport(result) {
  const lines = [`Title assets in ${TITLE_DIR}/ (WebP ${MAX_LONG_SIDE} px or less, MP3 ${kb(MUSIC_BUDGET_BYTES)} or less)`];
  for (const image of IMAGES) {
    const file = result.files[image.webp];
    const label = `  ${image.webp.padEnd(24)}`;
    if (file !== undefined) {
      const how = result.converted.includes(image.webp) ? `converted from ${image.png}` : 'already there';
      lines.push(`${label} ok        ${`${file.width}x${file.height}`.padEnd(10)} ${kb(file.bytes).padStart(9)}  ${how}`);
    } else {
      lines.push(`${label} -         optional, not present`);
    }
  }
  const theme = result.files[THEME_FILE];
  if (theme !== undefined) {
    const how = result.converted.includes(THEME_FILE) ? 'encoded with ffmpeg' : 'already there';
    lines.push(`  ${THEME_FILE.padEnd(24)} ok                    ${kb(theme.bytes).padStart(9)}  ${how}`);
  } else {
    lines.push(`  ${THEME_FILE.padEnd(24)} -         optional, not present`);
  }
  lines.push(`Images: ${kb(result.imageBytes)} of the ${kb(IMAGE_BUDGET_BYTES)} budget. Music: ${kb(result.musicBytes)} of the ${kb(MUSIC_BUDGET_BYTES)} budget.`);
  for (const warning of result.warnings) lines.push(`Warning: ${warning}`);
  for (const error of result.errors) lines.push(`ERROR: ${error}`);
  return lines.join('\n');
}

function main() {
  const result = run();
  console.log(formatReport(result));
  if (result.changed) {
    const swFile = path.join(ROOT, 'sw.js');
    const bumped = bumpVersion(fs.readFileSync(swFile, 'utf8'));
    fs.writeFileSync(swFile, bumped);
    const hashed = spawnSync(process.execPath, [path.join(ROOT, 'scripts/precache-hash.mjs')], { encoding: 'utf8' });
    const version = bumped.match(/const APP_VERSION = '(\d+)';/)?.[1];
    if (hashed.status === 0) {
      console.log(`\nShipped files changed: APP_VERSION is now ${version} and precache-hash.txt is refreshed.`);
    } else {
      console.log(`\nAPP_VERSION is now ${version}, but the precache hash could not be refreshed:`);
      console.log((hashed.stderr || hashed.stdout || '').trim());
      console.log('Run `npm run precache-hash` once that is fixed.');
      process.exitCode = 1;
    }
  }
  if (!result.ok) process.exitCode = 1;
}

if (process.argv[1] !== undefined && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
