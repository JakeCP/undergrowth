// Dev script: turns the trading post's painted pictures into the WebP
// files the game ships, and keeps js/ui/shop-assets.js and the service
// worker's precache list in step with what is on disk. Modelled on
// scripts/map-assets.mjs.
//
//   node scripts/shop-assets.mjs
//
// Sources (PNG, git-ignored; each one optional, docs/art/shop-prompts.md
// says how they were made):
//   assets/shop/shop-interior.png  the back of the shop, 3:2, no characters
//   assets/shop/shop-counter.png   the counter, 3:2, on a transparent ground
//
// Both are shrunk to 1280 px wide. The counter keeps its alpha channel as
// it is: it is a hard mask, and the colour under its transparent pixels
// is never flattened or matted onto anything. The two are encoded at the
// highest quality that keeps them at BUDGET_BYTES together. The shop
// shows the painted scene only when both exist (js/ui/shop-view.js);
// until then it keeps the scene drawn in code. Running this twice
// changes nothing. This script itself is never precached.
//
// When anything shipped has changed it also bumps APP_VERSION in sw.js
// and refreshes precache-hash.txt, as tests/pwa.test.mjs expects. This
// is not part of the deploy: there is still no build step.
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { pngSize, webpSize, bumpVersion } from './textures.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export const SHOP_DIR = 'assets/shop';
export const LIST_FILE = 'js/ui/shop-assets.js';
/** The two pictures together, at most, in bytes. */
export const BUDGET_BYTES = 300 * 1024;
/** Shipped width in pixels. */
export const WIDTH = 1280;
/** Qualities to try, best first, until the pair fits the budget. */
const QUALITIES = [82, 76, 70, 64, 58, 52, 46, 40];
const ALPHA_QUALITY = 90;

/**
 * The pictures, in list-file order. `alpha` marks the cut-out.
 * @type {readonly {key: 'interior'|'counter', name: string, alpha: boolean}[]}
 */
export const IMAGES = Object.freeze([
  { key: 'interior', name: 'shop-interior', alpha: false },
  { key: 'counter', name: 'shop-counter', alpha: true },
]);

/** @typedef {{interior?: string, counter?: string}} ShopAssets */

/**
 * The source of js/ui/shop-assets.js for these shipped files.
 * @param {ShopAssets} assets
 * @returns {string}
 */
export function shopAssetsSource(assets) {
  const lines = IMAGES
    .filter((img) => assets[img.key] !== undefined)
    .map((img) => `  ${img.key}: '${assets[img.key]}',`);
  return [
    '// Generated by scripts/shop-assets.mjs: the trading post\'s painted',
    '// pictures that exist as shipped WebP files under assets/shop/. Do not',
    '// edit by hand; run `node scripts/shop-assets.mjs` after adding or',
    '// removing a file.',
    '/** @type {Readonly<{interior?: string, counter?: string}>} */',
    lines.length === 0
      ? 'export const SHOP_ASSETS = Object.freeze({});'
      : `export const SHOP_ASSETS = Object.freeze({\n${lines.join('\n')}\n});`,
    '',
  ].join('\n');
}

/**
 * sw.js with its precache list listing exactly these shop files (sorted).
 * They go where the old ones were; the first time, before the title
 * files (which scripts/title-assets.mjs keeps last), else at the end.
 * Other entries are left as they are.
 * @param {string} sw the source of sw.js
 * @param {string[]} files shipped paths relative to the repo root
 * @returns {string}
 */
export function syncShopPrecache(sw, files) {
  const block = sw.match(/(const PRECACHE_URLS = \[\n)([\s\S]*?)(\];)/);
  if (block === null || block.index === undefined) {
    throw new Error('sw.js must declare const PRECACHE_URLS = [...]');
  }
  const lines = block[2].split('\n').slice(0, -1).map((line) => `${line}\n`);
  const ours = (/** @type {string} */ line) => /^[ \t]*'assets\/shop\//.test(line);
  let at = lines.findIndex(ours);
  const kept = lines.filter((line) => !ours(line));
  if (at < 0) at = kept.findIndex((line) => /^[ \t]*'assets\/title\//.test(line));
  if (at < 0) at = kept.length;
  const added = [...files].sort().map((file) => `  '${file}',\n`);
  kept.splice(at, 0, ...added);
  return sw.slice(0, block.index) + block[1] + kept.join('') + block[3]
    + sw.slice(block.index + block[0].length);
}

/**
 * @param {string} file
 * @param {string} content
 * @returns {boolean} true when the file had to be written
 */
function writeIfChanged(file, content) {
  if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === content) return false;
  fs.writeFileSync(file, content);
  return true;
}

/**
 * One cwebp run. For the cut-out the alpha channel is encoded as it is
 * (no -exact needed: cwebp never mattes the colour; it only may simplify
 * the colour under fully transparent pixels, which nothing shows).
 * @param {string} cwebp
 * @param {string} src
 * @param {string} dest
 * @param {{width: number, height: number}} to
 * @param {number} quality
 * @param {boolean} alpha
 * @returns {string|null} what went wrong, or null
 */
function encode(cwebp, src, dest, to, quality, alpha) {
  const args = ['-quiet', '-q', String(quality), '-m', '6', '-metadata', 'none'];
  if (alpha) args.push('-alpha_q', String(ALPHA_QUALITY));
  else args.push('-noalpha');
  args.push('-resize', String(to.width), String(to.height), src, '-o', dest);
  const done = spawnSync(cwebp, args, { encoding: 'utf8' });
  if (done.error !== undefined) return done.error.message;
  if (done.status !== 0) return (done.stderr || done.stdout || `exit status ${done.status}`).trim();
  if (!fs.existsSync(dest)) return 'no file was written';
  return null;
}

/**
 * The cwebp command on this machine, or null.
 * @returns {string|null}
 */
function findCwebp() {
  for (const cmd of ['cwebp', '/opt/homebrew/bin/cwebp']) {
    const probe = spawnSync(cmd, ['-version'], { encoding: 'utf8' });
    if (probe.error === undefined && probe.status === 0) return cmd;
  }
  return null;
}

/**
 * @typedef {object} ShopAssetsResult
 * @property {boolean} ok no errors
 * @property {string[]} converted shipped paths made on this run
 * @property {ShopAssets} assets what exists now
 * @property {Record<string, {width: number, height: number, bytes: number}>} files by shipped path
 * @property {string[]} missing pictures with neither source nor WebP
 * @property {number} quality the quality used on this run, or 0 when nothing was converted
 * @property {string[]} warnings
 * @property {string[]} errors
 * @property {number} totalBytes
 * @property {boolean} changed a shipped file changed: bump APP_VERSION
 *   and refresh the precache hash
 */

/**
 * Converts the sources under `root` when either is newer than its WebP,
 * then brings the list module and the precache list in `root`'s sw.js
 * up to date. It does not bump the version or touch the precache hash;
 * the command line does that.
 * @param {{root?: string, converter?: string|null}} [options]
 * @returns {ShopAssetsResult}
 */
export function run(options = {}) {
  const root = options.root ?? ROOT;
  const cwebp = options.converter === undefined ? findCwebp() : options.converter;
  /** @type {string[]} */
  const converted = [];
  /** @type {string[]} */
  const missing = [];
  /** @type {string[]} */
  const warnings = [];
  /** @type {string[]} */
  const errors = [];
  let changed = false;
  let quality = 0;

  const jobs = IMAGES.map((img) => ({
    ...img,
    src: path.join(root, SHOP_DIR, `${img.name}.png`),
    rel: `${SHOP_DIR}/${img.name}.webp`,
    dest: path.join(root, SHOP_DIR, `${img.name}.webp`),
  }));
  const sources = jobs.filter((j) => fs.existsSync(j.src));
  for (const j of jobs) if (!fs.existsSync(j.src) && !fs.existsSync(j.dest)) missing.push(j.rel);
  const stale = sources.some((j) => !fs.existsSync(j.dest) || fs.statSync(j.src).mtimeMs > fs.statSync(j.dest).mtimeMs);

  if (stale && cwebp === null) {
    errors.push('cwebp was not found, so the shop pictures were not converted. Install it (brew install webp) and run this again.');
  } else if (stale && cwebp !== null) {
    /** @type {Map<string, Buffer|null>} */
    const before = new Map(sources.map((j) => [j.dest, fs.existsSync(j.dest) ? fs.readFileSync(j.dest) : null]));
    /** @type {Map<string, {width: number, height: number}>} */
    const sizes = new Map();
    for (const j of sources) {
      const size = pngSize(fs.readFileSync(j.src));
      if (size === null) errors.push(`${SHOP_DIR}/${j.name}.png is not a PNG image: not converted`);
      else sizes.set(j.src, size);
    }
    const ready = sources.filter((j) => sizes.has(j.src));
    for (const q of QUALITIES) {
      quality = q;
      let failed = false;
      for (const j of ready) {
        const from = /** @type {{width: number, height: number}} */ (sizes.get(j.src));
        const width = Math.min(WIDTH, from.width);
        const to = { width, height: Math.max(1, Math.round((from.height * width) / from.width)) };
        const problem = encode(cwebp, j.src, j.dest, to, q, j.alpha);
        if (problem !== null) {
          errors.push(`${SHOP_DIR}/${j.name}.png could not be converted: ${problem}`);
          failed = true;
        }
      }
      if (failed) break;
      const total = ready.reduce((sum, j) => sum + fs.statSync(j.dest).size, 0);
      if (total <= BUDGET_BYTES) break;
    }
    for (const j of ready) {
      if (!fs.existsSync(j.dest)) continue;
      converted.push(j.rel);
      const was = before.get(j.dest);
      if (was === null || was === undefined || !was.equals(fs.readFileSync(j.dest))) changed = true;
    }
  }

  /** @type {ShopAssets} */
  const assets = {};
  /** @type {Record<string, {width: number, height: number, bytes: number}>} */
  const files = {};
  let totalBytes = 0;
  for (const j of jobs) {
    if (!fs.existsSync(j.dest)) continue;
    const data = fs.readFileSync(j.dest);
    const size = webpSize(data);
    assets[j.key] = j.rel;
    files[j.rel] = { width: size?.width ?? 0, height: size?.height ?? 0, bytes: data.length };
    totalBytes += data.length;
    if (size === null) warnings.push(`${j.rel} is not a WebP image`);
    else if (size.width > WIDTH) warnings.push(`${j.rel} is ${size.width} px wide, over ${WIDTH}`);
  }
  if (totalBytes > BUDGET_BYTES) {
    errors.push(`The shop pictures add up to ${kb(totalBytes)}, over the ${kb(BUDGET_BYTES)} budget`);
  }
  if (Object.keys(assets).length === 1) {
    warnings.push('Only one of the two shop pictures exists, so the shop keeps its drawn scene until the other arrives');
  }

  if (writeIfChanged(path.join(root, LIST_FILE), shopAssetsSource(assets))) changed = true;
  const swFile = path.join(root, 'sw.js');
  if (writeIfChanged(swFile, syncShopPrecache(fs.readFileSync(swFile, 'utf8'), Object.keys(files)))) changed = true;

  return { ok: errors.length === 0, converted, assets, files, missing, quality, warnings, errors, totalBytes, changed };
}

/**
 * @param {number} bytes
 * @returns {string}
 */
function kb(bytes) {
  return `${(bytes / 1024).toFixed(1)} KB`;
}

/**
 * The report printed after a run.
 * @param {ShopAssetsResult} result
 * @returns {string}
 */
export function formatReport(result) {
  const lines = [`Trading post pictures (${WIDTH} px wide)`];
  for (const [rel, file] of Object.entries(result.files)) {
    const how = result.converted.includes(rel) ? `converted at quality ${result.quality}` : 'already there';
    lines.push(`  ${rel.padEnd(30)} ${`${file.width}x${file.height}`.padEnd(10)} ${kb(file.bytes).padStart(9)}  ${how}`);
  }
  for (const rel of result.missing) lines.push(`  ${rel.padEnd(30)} -          no source: the shop keeps its drawn scene`);
  lines.push(`Total: ${kb(result.totalBytes)} of the ${kb(BUDGET_BYTES)} budget.`);
  for (const warning of result.warnings) lines.push(`Warning: ${warning}`);
  for (const error of result.errors) lines.push(`ERROR: ${error}`);
  return lines.join('\n');
}

function main() {
  const result = run();
  console.log(formatReport(result));
  if (result.changed) {
    const swFile = path.join(ROOT, 'sw.js');
    const bumped = bumpVersion(fs.readFileSync(swFile, 'utf8'));
    fs.writeFileSync(swFile, bumped);
    const hashed = spawnSync(process.execPath, [path.join(ROOT, 'scripts/precache-hash.mjs')], { encoding: 'utf8' });
    const version = bumped.match(/const APP_VERSION = '(\d+)';/)?.[1];
    if (hashed.status === 0) {
      console.log(`\nShipped files changed: APP_VERSION is now ${version} and precache-hash.txt is refreshed.`);
    } else {
      console.log(`\nAPP_VERSION is now ${version}, but the precache hash could not be refreshed:`);
      console.log((hashed.stderr || hashed.stdout || '').trim());
      console.log('Run `npm run precache-hash` once that is fixed.');
      process.exitCode = 1;
    }
  }
  if (!result.ok) process.exitCode = 1;
}

if (process.argv[1] !== undefined && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
